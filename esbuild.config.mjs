import esbuild from "esbuild";
import process from "process";
import { builtinModules } from 'node:module';
import copyStaticFiles from 'esbuild-copy-static-files';
import { spawnSync } from 'child_process';
import { rmSync } from 'node:fs';

const banner =
`/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = (process.argv[2] === 'production');

const nodeBuiltins = builtinModules.flatMap(moduleName =>
    moduleName.startsWith('node:') ? [moduleName] : [moduleName, `node:${moduleName}`]
);

const packageName = process.env.npm_package_name || 'meld-encrypt';
const versionString = process.env.npm_package_version || '0.0.0';

const distDir = prod
	? `./dist/${packageName}-${versionString}/${packageName}`
	: `./tests/test-vault/.obsidian/plugins/${packageName}`
;

const ctx = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ['src/main.ts'],
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...nodeBuiltins],
	format: 'cjs',
	target: 'es2018',
	charset: 'utf8',
	logLevel: "info",
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	minify: prod,
	outfile: `${distDir}/main.js`,
	plugins:[
		copyStaticFiles({
			src: './src/styles.css',
			dest: `${distDir}/styles.css`,
		}),
		copyStaticFiles({
			src: './manifest.json',
			dest: `${distDir}/manifest.json`,
		}),
	]
});

if (prod) {
	try {
		console.log(`Building production bundle ${packageName} v${versionString} ...`);
		await ctx.rebuild();
		const archive = `${packageName}-${versionString}.zip`;
		// Remove any previous archive so obsolete files cannot survive an update.
		rmSync(`./dist/${archive}`, { force: true });
		const result = spawnSync('zip', ['-r', `../${archive}`, packageName], {
			cwd: `./dist/${packageName}-${versionString}`,
			stdio: 'inherit',
		});
		if (result.error) throw result.error;
		if (result.status !== 0) throw new Error(`ZIP packaging failed (${result.signal ?? result.status})`);
	} finally {
		await ctx.dispose();
	}
}else{
	console.log('Building development bundle...');
	await ctx.watch();
}
